async function isAdmin(openid) {
  try {
    await ensureCollection('admins')
    const res = await db.collection('admins').where({ _openid: openid }).limit(1).get()
    return res.data.length > 0
  } catch (e) {
    return false
  }
}

exports.main = async event => {
  const apiKey = process.env.ZHIPU_API_KEY
  if (!apiKey) {
    return {
      ok: false,
      msg: '云函数未读取到 ZHIPU_API_KEY',
      detail: '请在云开发控制台 → 云函数 → assistant → 配置 → 环境变量中添加 ZHIPU_API_KEY 后重试'
    }
  }

  const { OPENID } = cloud.getWXContext()

  try {
    const action = event.action

    // ===== 附近宠物医院（腾讯位置服务 POI，环境变量或本地 tencent_key.js） =====
    if (action === 'nearbyHospitals') {
      const lat = Number(event.lat)
      const lng = Number(event.lng)
      if (!isFinite(lat) || !isFinite(lng)) return { ok: false, msg: '定位参数缺失' }
      try {
        const list = await searchNearbyHospitals(lat, lng)
        return { ok: true, data: list }
      } catch (e) {
        console.warn('[assistant] 附近宠物医院检索失败', e && e.message)
        // detail 会拼在前端提示里，方便直接看到 Key/配额等真实原因
        return { ok: false, msg: '附近医院检索失败', detail: (e && e.message) || '未知错误' }
      }
    }

    // ===== 知识库管理（仅管理员）：RAG 私有知识库增删查 =====
    if (action === 'kbList' || action === 'kbAdd' || action === 'kbRemove') {
      await ensureCollection(KB_COLLECTION)
      if (!(await isAdmin(OPENID))) return { ok: false, msg: '无管理员权限' }

      if (action === 'kbList') {
        const res = await db
          .collection(KB_COLLECTION)
          .orderBy('createdAt', 'desc')
          .limit(1000)
          .get()
        return { ok: true, data: res.data }
      }
      if (action === 'kbAdd') {
        const doc = event.doc || {}
        const title = String(doc.title || '').trim().slice(0, 40)
        const content = String(doc.content || '').trim().slice(0, 2000)
        const tags = String(doc.tags || '').trim().slice(0, 50)
        if (!title || !content) return { ok: false, msg: '标题和内容不能为空' }
        const res = await db
          .collection(KB_COLLECTION)
          .add({ data: { title, content, tags, createdAt: Date.now() } })
        return { ok: true, data: { _id: res._id } }
      }
      // kbRemove
      await db.collection(KB_COLLECTION).doc(event.id).remove()
      return { ok: true, data: { id: event.id } }
    }

    // ===== AI 问诊（默认） =====
    const { question = '', petProfile = {}, fileIDs = [] } = event

    // 本次问诊总耗时预算：云函数上限 60s，预留安全检查/检索/序列化余量
    const consultStartedAt = Date.now()
    const remainingMs = () => 52000 - (Date.now() - consultStartedAt)

    // 内容安全：问题文本违规直接拦截；openapi 不可用时放行（fail-open）
    try {
      const sec = await cloud.openapi.security.msgSecCheck({
        version: 2,
        scene: 2,
        openid: OPENID,
        content: question
      })
      const d = sec && sec.result
      if (d && d.suggest && d.suggest !== 'pass') {
        return { ok: false, msg: '问题内容涉嫌违规，请修改后重试' }
      }
    } catch (e) {
      console.warn('[assistant] msgSecCheck 不可用，放行', e && e.message)
    }

    // 下载图片并转 base64
    const imageUrls = []
    for (const fileID of fileIDs.slice(0, MAX_IMAGES)) {
      const file = await cloud.downloadFile({ fileID })
      if (file.fileContent.length > 4 * 1024 * 1024) {
        return { ok: false, msg: '图片过大，请压缩后重试' }
      }
      imageUrls.push(`data:image/jpeg;base64,${file.fileContent.toString('base64')}`)
    }

    // RAG 检索 + 知识库播种 + 情感分析
    await ensureKbSeed()
    const kbDocs = await searchKb(question, 3).catch(() => [])
    const mood = analyzeSentiment(question).mood

    const userText = `${buildPetText(petProfile)}\n\n用户描述：${question || '（仅上传了照片，请结合照片分析）'}`
    const sysPrompt = buildSystemPrompt(imageUrls.length > 0, kbDocs, mood)

    // ---- 带图：视觉模型「观察师 → 审查员」两阶段诊断（准确优先，不计延迟） ----
    if (imageUrls.length) {
      const content = imageUrls.map(url => ({ type: 'image_url', image_url: { url } }))
      content.push({ type: 'text', text: userText })

      // 阶段一：观察师逐图做详尽影像学观察（失败不致命，可降级直判）
      const obs = await observeImage(content)

      // 用「用户文字 + 观察师的关键词/倾向」联合检索知识库，纯图片也能命中
      const kbQuery = `${question || ''} ${((obs && obs.keywords) || []).join(' ')}`.trim()
      const imgKbDocs = kbQuery ? await searchKb(kbQuery, 5).catch(() => []) : []

      // 阶段二：审查员结合图片、观察报告与知识库资料，交叉验证后输出最终诊断
      const reportText = obs && obs.report ? obs.report : ''
      const reviewUser =
        `${buildPetText(petProfile)}\n\n用户描述：${question || '（仅上传了照片，请结合照片分析）'}` +
        `\n\n【影像观察报告（初判模型输出，供交叉参考）】\n${reportText || '（首轮观察未产出，直接基于图片判断）'}`
      const reviewContent = content
        .slice(0, -1)
        .concat([{ type: 'text', text: reviewUser }])

      const imgSysPrompt = buildSystemPrompt(true, imgKbDocs, mood)

      let lastErr = null
      for (const model of VISION_MODELS) {
        try {
          const res = await callZhipu({
            model,
            messages: [
              { role: 'system', content: imgSysPrompt },
              {
                role: 'user',
                content:
                  model === 'glm-4v-flash'
                    ? reviewContent.slice(0, 1).concat(reviewContent.slice(-1))
                    : reviewContent
              }
            ],
            temperature: 0.15,
            // 免费视觉模型 max_tokens 上限为 1024（API 限制 [1,1024]），按满配使用
            max_tokens: 1024,
            timeoutMs: 25000
          })
          const data = parseJson(res.choices[0].message.content)
          return {
            ok: true,
            model,
            data: {
              level: data.level || 'yellow',
              summary: toText(data.summary),
              content: buildContent(data),
              followUp: (Array.isArray(data.followUp) ? data.followUp : []).map(toText).filter(Boolean).slice(0, 3)
            }
          }
        } catch (e) {
          lastErr = e
          console.error(`[assistant] ${model} 调用失败:`, e && e.message)
        }
      }
      throw lastErr || new Error('模型调用失败')
    }

    // ---- 纯文本：Agent 工具调用循环（glm-4-flash 支持 Function Calling） ----
    const messages = [
      { role: 'system', content: sysPrompt },
      { role: 'user', content: userText }
    ]
    let finalContent = ''
    for (let round = 0; round < MAX_TOOL_ROUNDS; round++) {
      // 预算耗尽：停止发起新一轮模型调用，用已获取的信息兜底回复
      if (remainingMs() < 12000) break
      const res = await callZhipuWithRetry(
        {
          model: TEXT_MODEL,
          messages,
          tools: TOOLS,
          temperature: 0.2,
          max_tokens: 1024,
          // 单轮超时从默认 18s 提至 25s：免费模型高峰期推理更慢
          timeoutMs: Math.min(25000, remainingMs())
        },
        remainingMs
      )
      const msg = res.choices[0].message
      // 模型请求调用工具：本地执行后把结果回填，继续下一轮
      if (msg.tool_calls && msg.tool_calls.length) {
        messages.push({ role: 'assistant', content: msg.content || '', tool_calls: msg.tool_calls })
        for (const tc of msg.tool_calls) {
          let result
          try {
            const args = JSON.parse(tc.function.arguments || '{}')
            result = await runTool(tc.function.name, args)
            console.log('[assistant] 工具调用', tc.function.name, JSON.stringify(result).slice(0, 200))
          } catch (e) {
            result = { ok: false, msg: String((e && e.message) || e) }
          }
          messages.push({
            role: 'tool',
            tool_call_id: tc.id,
            content: JSON.stringify(result).slice(0, 3000)
          })
        }
        continue
      }
      finalContent = msg.content || ''
      break
    }

    let data
    if (finalContent) {
      data = parseJson(finalContent)
    } else {
      // 多轮工具调用后仍未产出结论：返回兜底结构
      data = {
        level: 'yellow',
        summary: '本次分析未能完成',
        analysis: 'AI 在获取资料后未能得出结论，请补充更详细的描述后重试。',
        diseases: [],
        care: [],
        visit: '如症状持续或加重，请及时就医。',
        forbid: [],
        followUp: ['请补充更详细的症状描述']
      }
    }

    return {
      ok: true,
      model: TEXT_MODEL,
      data: {
        level: data.level || 'yellow',
        summary: toText(data.summary),
        content: buildContent(data),
        followUp: (Array.isArray(data.followUp) ? data.followUp : []).map(toText).filter(Boolean).slice(0, 3)
      }
    }
  } catch (e) {
    console.error('[assistant]', e)
    return {
      ok: false,
      msg: 'AI服务繁忙，请稍后重试',
      detail: String((e && e.message) || e)
    }
  }
}
