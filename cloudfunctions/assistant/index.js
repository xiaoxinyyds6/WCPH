async function ensureKbSeed() {
  try {
    await ensureCollection(KB_COLLECTION)
    await ensureCollection(KB_META_COLLECTION)

    // 读取已播种到的种子版本（meta 不存在视为 0，首次全量播种）
    let cur = 0
    try {
      const m = await db.collection(KB_META_COLLECTION).doc('seed').get()
      cur = (m && m.data && m.data.version) || 0
    } catch (e) {
      // meta 文档不存在，按 0 处理
    }

    const pending = KB_SEEDS.filter(s => (s.v || 1) > cur)
    if (!pending.length) return

    // 分页取出全部现有标题去重（云端 get 单次有上限，翻页取全）
    const existing = new Set()
    for (let skip = 0; ; skip += 500) {
      const page = await db
        .collection(KB_COLLECTION)
        .field({ title: true })
        .skip(skip)
        .limit(500)
        .get()
      const list = (page && page.data) || []
      list.forEach(d => existing.add(String(d.title || '').trim()))
      if (list.length < 500) break
    }

    const now = Date.now()
    const toAdd = []
    for (const s of pending) {
      if (existing.has(s.title)) continue
      toAdd.push({ title: s.title, tags: s.tags, content: s.content, seeded: true, v: s.v || 1, createdAt: now })
      existing.add(s.title)
    }

    // 批量写入：云函数端 add 支持数组，按 100 条/批执行；整批失败降级逐条重试
    let added = 0
    for (let i = 0; i < toAdd.length; i += 100) {
      const chunk = toAdd.slice(i, i + 100)
      try {
        await db.collection(KB_COLLECTION).add({ data: chunk })
        added += chunk.length
      } catch (e2) {
        console.warn(`[assistant] 知识库批量播种失败 chunk[${i}]`, e2 && e2.message)
        for (const doc of chunk) {
          try {
            await db.collection(KB_COLLECTION).add({ data: doc })
            added++
          } catch (e3) {
            console.warn('[assistant] 知识库单条播种失败', doc.title, e3 && e3.message)
          }
        }
      }
    }

    // 记录已播种版本（set 为 upsert，不存在则创建）
    try {
      await db.collection(KB_META_COLLECTION).doc('seed').set({ data: { version: KB_SEED_VERSION } })
    } catch (e) {
      await db.collection(KB_META_COLLECTION).add({ data: { _id: 'seed', version: KB_SEED_VERSION } })
    }
    console.log('[assistant] 知识库种子文档增量写入', added, '条')
  } catch (e) {
    console.warn('[assistant] 知识库播种失败（不影响问诊）', e && e.message)
  }
}

// 关键词分词：按空格/标点拆词 + 中文2字滑窗（bigram），提高召回
function tokenize(query) {
  const t = String(query || '').toLowerCase()
  const terms = new Set()
  t.split(/[\s,，。.!?？;；、]+/).forEach(w => {
    if (w.length >= 2) terms.add(w)
  })
  const cjk = t.replace(/[^\u4e00-\u9fa5a-z0-9]/g, '')
  for (let i = 0; i + 2 <= cjk.length; i++) terms.add(cjk.slice(i, i + 2))
  return [...terms].filter(w => w.length >= 2).slice(0, 30)
}

// 分页读取知识库全部文档（云端 get 单次有上限，翻页取全）
async function fetchAllKbDocs() {
  const docs = []
  for (let skip = 0; ; skip += 500) {
    const page = await db.collection(KB_COLLECTION).skip(skip).limit(500).get()
    const list = (page && page.data) || []
    docs.push(...list)
    if (list.length < 500) break
  }
  return docs
}

// 打分检索：标题命中3分、正文命中1分，返回得分最高的前 N 条
async function searchKb(query, topN) {
  const terms = tokenize(query)
  if (!terms.length) return []
  const docs = await fetchAllKbDocs()
  return docs
    .map(d => {
      const title = String(d.title || '')
      const content = String(d.content || '')
      let score = 0
      terms.forEach(t => {
        if (title.indexOf(t) >= 0) score += 3
        if (content.indexOf(t) >= 0) score += 1
      })
      return { d, score }
    })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, topN || 3)
    .map(x => ({ title: x.d.title, content: String(x.d.content || '').slice(0, 1200), score: x.score }))
}

// ================= 情感分析（规则法）：识别焦虑语气 =================

const ANXIOUS_WORDS = [
  '担心', '害怕', '急', '救命', '救救', '疼', '痛', '哭', '崩溃', '不行了',
  '难受', '严重吗', '恶化', '吐血', '抽搐', '瘫', '危险', '怎么办', '吓死'
]

function analyzeSentiment(text) {
  const t = String(text || '')
  const hits = ANXIOUS_WORDS.filter(w => t.indexOf(w) >= 0)
  return { mood: hits.length ? 'anxious' : 'neutral', hits: hits.slice(0, 5) }
}

