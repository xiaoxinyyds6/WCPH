function httpsGetJson(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { timeout: 8000 }, res => {
      let data = ''
      res.on('data', c => (data += c))
      res.on('end', () => {
        try {
          resolve(JSON.parse(data))
        } catch (e) {
          reject(new Error('地图服务响应解析失败'))
        }
      })
    })
    req.on('error', reject)
    req.on('timeout', () => req.destroy(new Error('地图服务请求超时')))
  })
}

// 按用户坐标检索 5km 内「宠物医院」POI，返回规范化列表（距离由前端按坐标计算）
async function fetchNearbyHospitals(key, lat, lng) {
  const url =
    'https://apis.map.qq.com/ws/place/v1/search?keyword=' +
    encodeURIComponent('宠物医院') +
    `&boundary=nearby(${lat},${lng},5000,1)&orderby=1&page_size=20&key=${encodeURIComponent(key)}`
  const res = await httpsGetJson(url)
  if (!res || res.status !== 0) {
    // 带上腾讯侧错误码与描述，便于前端展示与排查（110/112/113/121/311 等）
    throw new Error(`地图服务返回异常(${(res && res.status) || 'unknown'}): ${(res && res.message) || '未知原因'}`)
  }
  return ((res.data && res.data) || [])
    .map(it => ({
      name: it.title || '宠物医院',
      addr: it.address || '',
      lat: it.location ? it.location.lat : null,
      lng: it.location ? it.location.lng : null,
      // 腾讯 POI 的 tel 可能是「18922849001;0755-88363589」多号码串，取第一个可拨号码
      phone: String(it.tel || '')
        .split(/[;,，、\s]+/)
        .filter(Boolean)[0] || ''
    }))
    .filter(h => h.lat != null && h.lng != null)
}

// 检索附近医院：环境变量 Key 失效（格式错误/未授权/配额用尽）时自动用本地 Key 重试一次
async function searchNearbyHospitals(lat, lng) {
  const keys = [TENCENT_MAP_KEY, LOCAL_MAP_KEY].filter((k, i, arr) => k && arr.indexOf(k) === i)
  if (!keys.length) {
    throw new Error('地图服务未配置（TENCENT_MAP_KEY 环境变量与本地 tencent_key.js 均缺失）')
  }
  let lastErr = null
  for (const key of keys) {
    try {
      const list = await fetchNearbyHospitals(key, lat, lng)
      if (list.length) return list
      lastErr = lastErr || new Error('附近 5 公里内未检索到宠物医院')
    } catch (e) {
      lastErr = e
    }
  }
  throw lastErr
}

function buildPetText(petProfile) {
  const p = petProfile || {}
  const breed = [p.category, p.breed].filter(Boolean).join(' ')
  const parts = [
    breed && `品种：${breed}`,
    p.gender && `性别：${p.gender}`,
    p.weight != null && `体重：${p.weight}kg`,
    p.birthDate && `出生日期：${p.birthDate}`,
    p.neutered && `绝育：${p.neutered}`,
    p.vaccinated && `疫苗：${p.vaccinated}`,
    p.dewormed && `驱虫：${p.dewormed}`
  ].filter(Boolean)
  return `宠物档案：${parts.length ? parts.join('；') : '暂无'}`
}

function parseJson(raw) {
  const cleaned = String(raw || '').replace(/```json|```/g, '').trim()
  const start = cleaned.indexOf('{')
  const end = cleaned.lastIndexOf('}')
  if (start < 0 || end < 0) throw new Error('模型未返回有效JSON')
  return JSON.parse(cleaned.slice(start, end + 1))
}

function toText(v) {
  if (v === null || v === undefined) return ''
  if (typeof v === 'string') return v.trim()
  if (Array.isArray(v)) return v.map(toText).filter(Boolean).join('\n')
  if (typeof v === 'object') {
    return Object.keys(v)
      .map(k => toText(v[k]))
      .filter(Boolean)
      .join('\n')
  }
  return String(v)
}

// 统一拼装成前端展示的三段式文本，兼容模型返回的各种结构
function buildContent(data) {
  const lines = []
  const analysis = toText(data.analysis)
  if (analysis) lines.push(`【分析】${analysis}`)

  const diseases = toText(data.diseases)
  if (diseases) lines.push(`【可能病症】\n${diseases}`)

  const care = toText(data.care)
  const visit = toText(data.visit)
  const forbid = toText(data.forbid)
  if (care || visit || forbid) {
    const t = ['【治疗意见】']
    if (care) t.push(`· 家庭护理：${care}`)
    if (visit) t.push(`· 就医建议：${visit}`)
    if (forbid) t.push(`· 禁止事项：${forbid}`)
    lines.push(t.join('\n'))
  }

  // 药物类别建议：只给类别方向，反复强调不能自行用药
  const meds = toText(data.meds)
  if (meds) {
    lines.push(`【可用药类（仅供与兽医沟通参考，切勿自行用药）】\n${meds}`)
  }

  // 兜底：模型没有按新字段返回时，沿用旧 content 字段
  if (!lines.length) {
    const fallback = toText(data.content)
    if (fallback) lines.push(fallback)
  }

  lines.push('以上建议不能替代执业兽医的现场诊断，若症状加重请立即就医。')
  return lines.join('\n\n')
}

