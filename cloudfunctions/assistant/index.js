// ================= 图像问诊「观察师-审查员」两阶段诊断 =================

// 观察师：只做详尽的影像学观察，不做最终诊断（越细致越利于后续精准判断）
const OBSERVER_PROMPT = [
  '你是资深宠物医学影像观察师。请对每张图片做严谨、克制的临床观察，输出 JSON：',
  '1. 若图中含文字类资料（化验单、检查报告、处方单、疫苗本等），先逐行完整转录。',
  '2. 逐张描述可见信息：物种/品种线索、拍摄部位、病灶的分布/数量/颜色/边界/表面/渗出/痂皮/周围组织、姿态与精神线索；只描述看得到的，看不到的明确写「图中不可见」。',
  '3. report 字段：汇总关键视觉发现，并给出最可疑的 2-3 个方向（仅倾向，不给最终诊断）。',
  '4. keywords 字段：2-8 个中文医学关键词（含物种、部位、病灶形态），用于检索知识库。',
  '输出格式：{"keywords":["..."],"report":"..."}，只输出 JSON。'
].join('\n')

async function observeImage(content) {
  for (const model of VISION_MODELS) {
    try {
      const res = await callZhipu({
        model,
        messages: [
          { role: 'system', content: OBSERVER_PROMPT },
          {
            role: 'user',
            content:
              model === 'glm-4v-flash'
                ? content.slice(0, 1).concat(content.slice(-1))
                : content
          }
        ],
        temperature: 0.1,
        max_tokens: 900,
        timeoutMs: 20000
      })
      const d = parseJson(res.choices[0].message.content)
      const report = toText(d.report || d.overall || '')
      const keywords = (Array.isArray(d.keywords) ? d.keywords : [])
        .map(x => String(x).trim())
        .filter(Boolean)
        .slice(0, 8)
      if (!report && !keywords.length) continue
      return { model, report, keywords }
    } catch (e) {
      console.warn('[assistant] 观察师模型失败，尝试下一个', model, e && e.message)
    }
  }
  return null
}

