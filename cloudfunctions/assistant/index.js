function callZhipu(payload) {
  return new Promise((resolve, reject) => {
    // 单次模型调用超时（可被 payload.timeoutMs 覆盖）：观察师/审查员推理耗时更长
    const timeoutMs = payload.timeoutMs || 18000
    delete payload.timeoutMs
    const body = JSON.stringify(payload)
    const req = https.request(
      {
        hostname: 'open.bigmodel.cn',
        path: '/api/paas/v4/chat/completions',
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${process.env.ZHIPU_API_KEY}`,
          'Content-Length': Buffer.byteLength(body)
        },
        timeout: timeoutMs
      },
      res => {
        let data = ''
        res.on('data', c => (data += c))
        res.on('end', () => {
          let parsed = null
          try {
            parsed = JSON.parse(data)
          } catch (e) {
            // 非 JSON 响应，交给下面统一报错
          }
          if (res.statusCode >= 400 || (parsed && parsed.error)) {
            const apiMsg =
              (parsed && parsed.error && (parsed.error.message || parsed.error.code)) ||
              String(data).slice(0, 300)
            return reject(new Error(`HTTP ${res.statusCode}: ${apiMsg}`))
          }
          if (!parsed) {
            return reject(new Error(`模型响应解析失败: ${String(data).slice(0, 200)}`))
          }
          resolve(parsed)
        })
      }
    )
    req.on('error', reject)
    req.on('timeout', () => req.destroy(new Error('模型请求超时')))
    req.write(body)
    req.end()
  })
}

// 智谱免费模型高峰期偶发拥塞导致单次调用超时：识别超时错误后在总预算内立即重试一次
function isTimeoutErr(e) {
  return String((e && e.message) || e).indexOf('模型请求超时') !== -1
}

// remainingMs：返回本次问诊剩余可用毫秒数的函数；预算不足 16s 时不再重试，直接抛出
async function callZhipuWithRetry(payload, remainingMs) {
  const firstMs = payload.timeoutMs
  try {
    return await callZhipu(payload)
  } catch (e) {
    if (!isTimeoutErr(e)) throw e
    const budget = typeof remainingMs === 'function' ? remainingMs() : 0
    if (budget < 16000) throw e
    console.warn('[assistant] 模型请求超时，预算内重试一次')
    return callZhipu(
      Object.assign({}, payload, { timeoutMs: Math.min(firstMs || 15000, 15000, budget - 1000) })
    )
  }
}

