async function runTool(name, args) {
  if (name === 'get_weather') {
    if (!args || !args.city) return { ok: false, msg: '缺少城市参数' }
    return getWeather(String(args.city))
  }
  if (name === 'search_kb') {
    const docs = await searchKb((args && args.query) || '', 3)
    return { ok: true, docs }
  }
  return { ok: false, msg: `未知工具：${name}` }
}

